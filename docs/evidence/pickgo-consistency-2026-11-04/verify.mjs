import {Browser} from '../../.agents/skills/design-taste-frontend/scripts/lib/cdp.mjs';
import {createServer} from '../../experiments/pickup-board/server.mjs';
import {RecommendationBoard} from '../../experiments/pickup-board/recommendation/board.mjs';
import {syntheticProvider} from '../../experiments/pickup-board/recommendation/providers.mjs';
import {PLACES} from '../../experiments/pickup-board/domain.mjs';
import {mkdirSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const out='work/pickgo-consistency';
const board=new RecommendationBoard(Date.now,()=>performance.now(),syntheticProvider);
const server=createServer(board);await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;const browser=await Browser.launch();const evidence=[];
const wait=async(p,fn)=>{for(let i=0;i<50;i++){if(await p.eval(fn))return;await new Promise(r=>setTimeout(r,150));}throw Error('Timed out '+fn);};
try {
 for(const [width,height] of [[1440,900],[768,1024],[390,844]]) {
  const driver=board.create(PLACES[0]),rider=board.join(driver.id,driver.invite);
  const p=await browser.newPage({width,height});await p.goto(base+'/');
  await p.eval(s=>sessionStorage.setItem('pickupSession',JSON.stringify(s)),rider);
  await p.goto(base+'/phone');await wait(p,()=>!document.querySelector('#share').disabled);
  assert.equal(await p.eval(()=>document.querySelector('#consent').hidden),false);await p.eval(()=>document.querySelector('#share').focus());assert.equal(await p.eval(()=>getComputedStyle(document.querySelector('#share')).outlineColor),'rgb(22, 22, 22)');
  await p.eval(()=>document.querySelector('#decline').click());await wait(p,()=>document.querySelector('#message').textContent.includes('동의하지 않았'));
  await p.screenshot({path:`${out}/phone-consent-${width}.jpg`,fullPage:true});
  assert.equal(await p.eval(()=>document.documentElement.scrollWidth>innerWidth),false);
  await p.eval(()=>document.querySelector('#stop').click());
  await p.eval(s=>sessionStorage.setItem('pickupSession',JSON.stringify(s)),driver);
  await p.goto(base+'/proximity');await wait(p,()=>!document.querySelector('#demoNear').disabled);
  await p.eval(()=>document.querySelector('#demoNear').click());await wait(p,()=>document.querySelector('#proximityState').textContent.includes('근처입니다'));
  evidence.push({width,near:await p.eval(()=>document.querySelector('#proximityState').textContent)});
  await p.eval(()=>document.querySelector('#demoFar').click());await wait(p,()=>document.querySelector('#proximityState').textContent.includes('멀어요'));await p.eval(()=>document.querySelector('#demoDenied').click());assert.match(await p.eval(()=>document.querySelector('#proximityReason').textContent),/권한 거부/);
  await p.screenshot({path:`${out}/proximity-denied-${width}.jpg`,fullPage:true});
  assert.equal(await p.eval(()=>document.documentElement.scrollWidth>innerWidth),false);
  await p.goto(base+'/recommendation');assert.notEqual(await p.eval(()=>getComputedStyle(document.querySelector('#message')).display),'none');await wait(p,()=>!document.querySelector('#west').disabled);
  await p.eval(()=>document.querySelector('#west').click());
  const q=await browser.newPage({width,height});await q.goto(base+'/');await q.eval(s=>sessionStorage.setItem('pickupSession',JSON.stringify(s)),rider);
  await q.goto(base+'/recommendation');await wait(q,()=>!document.querySelector('#east').disabled);await q.eval(()=>document.querySelector('#east').click());
  await wait(p,()=>!document.querySelector('#calculate').disabled);await p.eval(()=>document.querySelector('#calculate').click());
  await wait(p,()=>document.querySelectorAll('.candidate').length>0);
  await p.screenshot({path:`${out}/recommendation-candidates-${width}.jpg`,fullPage:true});
  assert.equal(await p.eval(()=>document.documentElement.scrollWidth>innerWidth),false);
  const candidateCount=await p.eval(()=>document.querySelectorAll('.candidate').length);
  await p.eval(()=>document.querySelector('.candidate:not(:disabled)').click());
  await wait(p,()=>!document.querySelector('#proposal').hidden);
  await p.eval(()=>document.querySelector('#withdraw').click());
  await wait(p,()=>document.querySelector('#proposal').hidden);
  await p.eval(()=>document.querySelector('#stop').click());await q.eval(()=>document.querySelector('#stop').click());
  await p.eval(()=>document.querySelector('.support-header .button').click());await wait(p,()=>location.pathname==='/');
  evidence.push({width,candidateCount,consentDecline:true,overflow:false,proposalWithdrawal:true,backLink:true});
  await p.close();await q.close();
 }
 writeFileSync(`${out}/browser.json`,JSON.stringify(evidence,null,2));console.log(JSON.stringify(evidence));
}finally{await browser.close();await new Promise(r=>server.close(r));}
