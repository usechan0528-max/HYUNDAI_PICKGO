import {writeFileSync, mkdirSync} from 'node:fs';
import {history} from '../journey-context/demo/observations.mjs';
import {catalog} from '../journey-context/demo/content.mjs';
import {CoordinateStream} from '../journey-context/coordinate-stream.mjs';
import {recommend,QueuePolicy} from '../journey-context/core.mjs';

// Fixed synthetic profile only. No user preferences or measured coordinates.
const preferences={topics:{story:3,reflection:1},byPurpose:{commute:{reflection:4},errand:{reflection:-3}}};
const ids=['story','story2','pause','pause2'];
const items=ids.map(id=>catalog.find(c=>c.id===id));
if(items.some(c=>!c?.testOnly)||history.length!==2) throw Error('fixture contract changed');
const arr=v=>Array.isArray(v)?`{${v.map(arr).join(',')}}`:typeof v==='string'?JSON.stringify(v):String(v);
writeFileSync(new URL('app/src/main/java/org/example/j1listening/JourneyFixture.java',import.meta.url),`package org.example.j1listening;
// Generated by generate-journey-fixture.mjs from the existing demo fixture; synthetic only.
final class JourneyFixture {
 static final String[] IDS=${arr(ids)};
 static final double[][][] ROUTES=${arr(history.map(h=>h.points.map(p=>[p.latitude,p.longitude])))};
 static final long[] ENDED=${arr(history.map(h=>h.endedAtMs))};
 static final double[] TASTE=${arr(items.map(c=>preferences.topics[c.topic]??0))};
 static final double[][] PURPOSE_WEIGHTS=${arr(history.map(h=>items.map(c=>preferences.byPurpose[h.confirmedPurpose]?.[c.topic]??0)))};
}
`);
// Compile generated assertions against Java: expected results are actual JS policy outputs.
const lines=['package org.example.j1listening;','public class JourneyParityTest { public static void main(String[] args) {'];
let assertions=0;
for(const branch of [1,-1]) for(const ending of ['arrival','disconnect','consent-revoked','permission-revoked','route-change','stale','off-route']) {
 const s=new CoordinateStream(),q=new QueuePolicy();let token,old,mode=null,recent=[],n=0;
 lines.push('{ JourneyDemo d=new JourneyDemo(); long token=0,old=0;');
 const step=(code,fn,now)=>{
  lines.push(code);fn();
  const c=s.context(history,now);
  if(c.status!=='hypothesis'&&mode==='journey'){q.next=null;mode=null;}
  const p=recommend({catalog,preferences,context:c,recent,currentId:q.current});
  if(p&&q.update(p.id,now))mode=p.reasons.mode;
  lines.push(`d.refresh(${now}); check(d.candidates.size()==${c.candidates.length} && d.reason.equals(${JSON.stringify(c.reason)}),"context ${n}"); check(d.next==${ids.indexOf(q.next)} && d.current==${ids.indexOf(q.current)} && d.changes==${q.changes},"queue ${n++}");`);assertions+=2;
 };
 const begin=at=>step(`old=token; token=d.begin(${at});`,()=>{old=token;token=s.begin({source:'synthetic',profile:'owner',consent:true,permission:true,startedAtMs:at});q.next=null;},at);
 const point=(at,lat,lon)=>step(`check(d.point(token,${lat},${lon},${at},${at}),"accept");`,()=>s.push(token,{latitude:lat,longitude:lon,observedAtMs:at},at),at);
 begin(100);point(200,0,0);point(300,0,.001);
 // Equivalent selection-boundary validation, then consumption and refill.
 step('check(d.take(301)==0,"first story");',()=>{const id=q.consumeNext();recent.push(id);},301);
 point(400,branch*.001,.001);point(30400,branch*.001,.001);point(60400,branch*.001,.001);
 if(ending==='stale') step('',()=>{},90401);
 else if(ending==='off-route')point(60500,.02,.02);
 else step(`d.revoke(${JSON.stringify(ending)});`,()=>{s.revoke(ending);q.next=null;},60500);
 begin(100000);
 step('check(!d.point(old,0,0,100001,100001),"old generation");',()=>s.push(old,{latitude:0,longitude:0,observedAtMs:100001},100001),100001);
 point(100002,0,0);point(100003,0,.001);point(100004,-branch*.001,.001);
 lines.push('}');
}
lines.push(`System.out.println("JS/Java parity: ${assertions} context/queue assertions passed"); } static void check(boolean ok,String label) {if(!ok)throw new AssertionError(label);} }`);
mkdirSync(new URL('../../work/j1-android-journey/',import.meta.url),{recursive:true});
writeFileSync(new URL('../../work/j1-android-journey/JourneyParityTest.java',import.meta.url),lines.join('\n'));
console.log('Generated synthetic fixture and',assertions,'JS oracle assertions');
